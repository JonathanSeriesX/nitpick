import ColorScience
import Foundation

/// Dolby Vision display configuration for `DOLBY_CFG_DATA` (SPEC §5.10): tells the TV's DV display manager the real
/// panel white, black and primaries after the 1D LUT is calibrated to gamma 2.2 / D65. White is always D65.
public struct DolbyVisionDisplayConfig: Sendable, Hashable {
    /// A Dolby Vision bank: `dolby_cinema_bright` (1), `dolby_cinema_dark` (2), `dolby_game` (4).
    public var pictureMode: LGPicMode
    /// Measured white, cd/m², 100–4000.
    public var tMax: Double
    /// Measured black, cd/m², 0–0.99.
    public var tMin: Double
    public var tGamma: Double
    public var red: Chromaticity
    public var green: Chromaticity
    public var blue: Chromaticity

    public init(
        pictureMode: LGPicMode, tMax: Double, tMin: Double = 0.0001, tGamma: Double = 2.2,
        red: Chromaticity, green: Chromaticity, blue: Chromaticity
    ) {
        (self.pictureMode, self.tMax, self.tMin, self.tGamma) = (pictureMode, tMax, tMin, tGamma)
        (self.red, self.green, self.blue) = (red, green, blue)
    }

    /// bscpylgtv's XYZ → LMS matrix used for `TLMS2RGBmat`.
    static let xyzToLMS = Matrix3(rows: (0.4002, 0.7076, -0.0808), (-0.2263, 1.1653, 0.0457), (0, 0, 0.9182))

    /// `inverse(RGB→XYZ of the primaries with D65) × inverse(XYZ→LMS)`, row-major (2018 format only).
    public var lmsToRGB: Matrix3 {
        ColorSpacePrimaries(red: red, green: green, blue: blue, white: .d65).rgbToXYZ.inverse! * Self.xyzToLMS.inverse!
    }

    /// The API payload text, one block, CRLF lines, no file header (as bscpylgtv uploads it).
    /// - `.v2019`: `[PictureMode = N]`, `Tmax`, `Tmin`, `Tgamma`, `TPrimaries` (2019+ chips, including the B4's W24H).
    /// - `.v2018`: `PictureMode = N`, `Tmax`, `Tmin`, `Tgamma`, `ColorPrimaries`, `TLMS2RGBmat` (`%#.15g`).
    /// Which format a B4 accepts over the API is UNCONFIRMED (SPEC (b)21); the model profile picks `.v2019`.
    public func text(format: LGModelProfile.DolbyConfigFormat) throws -> String {
        guard let index = pictureMode.dolbyConfigIndex else {
            throw LGError.invalidPayload("\(pictureMode.rawValue) is not a Dolby Vision bank")
        }
        guard (100...4000).contains(tMax), (0...0.99).contains(tMin), tGamma.isFinite, tGamma > 0,
            [red, green, blue].allSatisfy({ (0...1).contains($0.x) && (0...1).contains($0.y) })
        else {
            throw LGError.invalidPayload("Dolby Vision config out of range (Tmax 100–4000, Tmin 0–0.99, primaries 0–1)")
        }
        let f4 = { (v: Double) in String(format: "%.4f", v) }
        let primaries = [red.x, red.y, green.x, green.y, blue.x, blue.y, 0.3127, 0.3290].map(f4).joined(separator: " ")
        var lines: [String]
        switch format {
        case .v2019:
            lines = [
                "[PictureMode = \(index)]", "Tmax = \(f4(tMax))", "Tmin = \(f4(tMin))", "Tgamma = \(tGamma)", "TPrimaries = \(primaries)",
            ]
        case .v2018:
            let m = lmsToRGB.m.map { String(format: "%#.15g", $0) }.joined(separator: " ")
            lines = [
                "PictureMode = \(index)", "Tmax = \(f4(tMax))", "Tmin = \(f4(tMin))", "Tgamma = \(tGamma)",
                "ColorPrimaries = \(primaries)", "TLMS2RGBmat = \(m)",
            ]
        }
        return lines.map { $0 + "\r\n" }.joined()
    }

    /// USB file `DolbyVision_UserDisplayConfiguration.txt` (2019 format) with its header; `date` like `2026-10-31`.
    public static func usbFile(_ configs: [DolbyVisionDisplayConfig], generator: String = "Nitpick", date: String) throws -> String {
        let header = [
            "# Dolby Vision User Display Configuration File", "# Generated by \(generator) on \(date)",
            "# Display: Unspecified", "# DM Version: ",
        ].map { $0 + "\r\n" }.joined()
        return try header + configs.map { try $0.text(format: .v2019) }.joined()
    }
}
